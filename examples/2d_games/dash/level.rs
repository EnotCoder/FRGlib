//! Мир уровня: сетка тайлов, её разбор и геометрия.
//!
//! Сама раскладка лежит в [`LEVEL`] строкой, чтобы читалась глазами: `.` — пусто,
//! `#` — шип, `=` — платформа, на которую можно приземлиться сверху. Строка 7
//! — земля, верхние строки висят в воздухе.

use frglib::Vec2;

/// Сторона тайла на экране. В файле 16, на экране 32 — ровно вдвое, так что
/// с `pixel_art` тайлы остаются чёткими.
pub const TILE: f32 = 32.0;

/// Сторона куба и шипа.
pub const BODY: f32 = TILE;

/// Мировая Y верха земли.
pub const GROUND: f32 = 400.0;

/// На какой высоте от низа окна стоит земля.
pub const GROUND_SCREEN: f32 = 0.75;

/// Уровень: 8 строк по 96 столбцов.
///
/// Точки вместо пробелов — намеренно: хвостовые пробелы редактор срежет, и
/// строки разъедутся.
pub const LEVEL: [&str; 8] = [
    "................................................................................................",
    "................................................................................................",
    "................................................................................................",
    "................................................................................................",
    "................................................................................................",
    "................................................................................................",
    "................................................................................................",
    "..........................##...........#......##..................#......#..............##......",
];

/// Строк и столбцов в [`LEVEL`].
pub const ROWS: usize = LEVEL.len();
pub const COLS: usize = LEVEL[0].len();

/// Верх уровня в мире: строка 7 должна встать на землю.
pub const LEVEL_TOP: f32 = GROUND - ROWS as f32 * TILE;

/// Что на клетке уровня.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum Tile {
    Empty,
    Spike,
    Platform,
}

/// Разбирает [`LEVEL`] в сетку. Делается один раз, а не на кадр.
pub fn parse() -> Vec<Vec<Tile>> {
    LEVEL
        .iter()
        .map(|row| {
            row.chars()
                .map(|c| match c {
                    '#' => Tile::Spike,
                    '=' => Tile::Platform,
                    _ => Tile::Empty,
                })
                .collect()
        })
        .collect()
}

/// Верх тайла в строке `row`.
pub fn top_of(row: usize) -> f32 {
    LEVEL_TOP + row as f32 * TILE
}

/// Прямоугольники по центру пересекаются?
pub fn hit(a: Vec2, a_half: Vec2, b: Vec2, b_half: Vec2) -> bool {
    (a.x - b.x).abs() < a_half.x + b_half.x && (a.y - b.y).abs() < a_half.y + b_half.y
}
